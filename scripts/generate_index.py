"""Generate the bundled skill index from category catalogs, without skill bodies."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
INDEX = Path("skills/tooling/index")
START = "<!-- index:catalog:start -->"
END = "<!-- index:catalog:end -->"
GENERATED = "<!-- Generated by scripts/generate_index.py; edit category catalogs instead. -->"
MAX_PAGE_CHARS = 2500
ENTRY = re.compile(r"^- \[([a-z0-9]+(?:-[a-z0-9]+)*)\]\(\1/SKILL\.md\) — (.+)$")


def catalog_directory(root: Path) -> Path:
    directory = root / INDEX / "references/catalog"
    for path in (root / INDEX, directory.parent, directory):
        if path.is_symlink():
            raise ValueError(f"Index output must not be a symlink: {path}")
    return directory


def snapshot_index(root: Path) -> dict[Path, bytes]:
    manifest = root / INDEX / "SKILL.md"
    if not manifest.exists():
        return {}
    directory = catalog_directory(root)
    result = {}
    for path in [manifest, *sorted(directory.glob("*.md"))]:
        if path.is_symlink():
            raise ValueError(f"Index output must not be a symlink: {path}")
        content = path.read_bytes()
        if path != manifest and not content.startswith(GENERATED.encode()):
            raise ValueError(f"Unmanaged index file; left untouched: {path}")
        result[path] = content
    return result


def restore_index(root: Path, snapshot: dict[Path, bytes]) -> None:
    directory = catalog_directory(root)
    for path in directory.glob("*.md"):
        if path not in snapshot and path.read_bytes().startswith(GENERATED.encode()):
            path.unlink()
    for path, content in snapshot.items():
        if not path.exists() or path.read_bytes() != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)


def read_category(category: Path) -> tuple[str, list[tuple[str, str, str]]]:
    source = category / "README.md"
    text = source.read_text(encoding="utf-8")
    if text.count("<!-- skills:start -->") != 1 or text.count("<!-- skills:end -->") != 1:
        raise ValueError(f"Expected one skills catalog block: {source}")
    block = text.split("<!-- skills:start -->")[1].split("<!-- skills:end -->")[0]
    title = next((line[2:] for line in text.splitlines() if line.startswith("# ")), category.name)
    entries, section, seen = [], "", set()
    for line in block.splitlines():
        if not line.strip() or line == "No skills yet.":
            continue
        if line.startswith("## "):
            section = line[3:]
            continue
        match = ENTRY.fullmatch(line)
        if not match:
            raise ValueError(f"Unsupported catalog entry in {source}: {line}")
        name, summary = match.groups()
        if name in seen:
            raise ValueError(f"Duplicate catalog entry '{name}' in {source}")
        if len(summary) > 300:
            raise ValueError(f"Catalog summary exceeds 300 characters: {category.name}/{name}")
        entries.append((section, name, summary))
        seen.add(name)
    actual = {path.parent.name for path in category.glob("*/SKILL.md") if path.is_file()}
    if seen != actual:
        raise ValueError(f"Catalog does not match {category.name}: missing={sorted(actual - seen)}, extra={sorted(seen - actual)}")
    return title, entries


def page_text(title, category, entries, offset, total, page, pages, next_page):
    lines = [GENERATED, f"# {title}", "", f"Page {page} of {pages}. Entries {offset + 1}-{offset + len(entries)} of {total}; {total - len(entries)} on other pages.", ""]
    previous = None
    for section, name, summary in entries:
        if section != previous:
            if section:
                if previous is not None:
                    lines.append("")
                lines.extend([f"## {section}", ""])
            previous = section
        lines.append(f"- `{name}` — {summary}")
    if next_page:
        lines.extend(["", f"Next page: `references/catalog/{category}-{next_page}.md` (relative to this skill)."])
    else:
        lines.extend(["", "End of this category catalog."])
    return "\n".join(lines) + "\n"


def render_index(root: Path) -> dict[Path, str]:
    manifest = root / INDEX / "SKILL.md"
    if not manifest.exists():
        return {}
    directory = catalog_directory(root)
    body = manifest.read_text(encoding="utf-8")
    if body.count(START) != 1 or body.count(END) != 1 or body.index(START) > body.index(END):
        raise ValueError(f"Expected one index catalog block: {manifest}")
    descriptions = {}
    for line in (root / "README.md").read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"\| \[([a-z0-9-]+)\]\(skills/\1/README.md\) \| (.+?) \| \d+ \|", line)
        if match:
            descriptions[match[1]] = match[2]
    output, routing = {}, []
    for category in sorted((root / "skills").iterdir()):
        if not category.is_dir():
            continue
        title, entries = read_category(category)
        if not entries:
            continue
        chunks, current, offset = [], [], 0
        for entry in entries:
            candidate = [*current, entry]
            # Reserve room for final page counts and the exact recovery path.
            estimate = page_text(title, category.name, candidate, offset, len(entries), 999999, 999999, 999999)
            if len(estimate) > MAX_PAGE_CHARS:
                if not current:
                    raise ValueError(f"Index entry cannot fit a page: {category.name}/{entry[1]}")
                chunks.append(current)
                offset += len(current)
                current = [entry]
                if len(page_text(title, category.name, current, offset, len(entries), 999999, 999999, 999999)) > MAX_PAGE_CHARS:
                    raise ValueError(f"Index entry cannot fit a page: {category.name}/{entry[1]}")
            else:
                current = candidate
        chunks.append(current)
        offset = 0
        for page, chunk in enumerate(chunks, 1):
            filename = f"{category.name}{'-' + str(page) if page > 1 else ''}.md"
            content = page_text(title, category.name, chunk, offset, len(entries), page, len(chunks), page + 1 if page < len(chunks) else None)
            if len(content) > MAX_PAGE_CHARS:
                raise ValueError(f"Index page exceeds {MAX_PAGE_CHARS} characters: {filename}")
            output[directory / filename] = content
            offset += len(chunk)
        skills_label = "skill" if len(entries) == 1 else "skills"
        pages_label = "page" if len(chunks) == 1 else "pages"
        routing.append(f"- [{title}](references/catalog/{category.name}.md) — {descriptions.get(category.name, title)} ({len(entries)} {skills_label}; {len(chunks)} {pages_label}).")
    before, rest = body.split(START)
    _, after = rest.split(END)
    output[manifest] = before + START + "\n\n" + "\n".join(routing) + "\n\n" + END + after
    return output


def index_errors(root: Path) -> list[str]:
    try:
        snapshot = snapshot_index(root)
        expected = render_index(root)
    except (OSError, UnicodeError, ValueError) as exc:
        return [f"index: {exc}"]
    errors = []
    for path, content in expected.items():
        if snapshot.get(path) != content.encode("utf-8"):
            errors.append(f"{path.relative_to(root)}: stale or missing; run uv run scripts/generate_index.py")
    for path in snapshot.keys() - expected.keys():
        errors.append(f"{path.relative_to(root)}: obsolete; run uv run scripts/generate_index.py")
    return errors


def update_index(root: Path) -> int:
    snapshot = snapshot_index(root)
    expected = render_index(root)
    changed = 0
    try:
        for path, content in expected.items():
            encoded = content.encode("utf-8")
            if snapshot.get(path) != encoded:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(encoded)
                changed += 1
        for path in snapshot.keys() - expected.keys():
            path.unlink()
            changed += 1
    except OSError as exc:
        try:
            restore_index(root, snapshot)
        except OSError as restore_error:
            raise OSError(f"Index update failed ({exc}); restoration failed ({restore_error})") from exc
        raise
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Reject stale output without writing")
    args = parser.parse_args()
    try:
        if args.check:
            errors = index_errors(ROOT)
            if errors:
                print(f"Index check failed: {len(errors)} issue(s). Run uv run scripts/generate_index.py.")
                return 1
            print("Index is current.")
        else:
            count = update_index(ROOT)
            print(f"Index refreshed: {count} file(s) changed; catalog pages limited to {MAX_PAGE_CHARS} characters.")
    except (OSError, UnicodeError, ValueError) as exc:
        message = str(exc)
        print(f"Index generation failed ({len(message)} characters): {message[:3000]}" + (" [remainder omitted]" if len(message) > 3000 else ""))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
